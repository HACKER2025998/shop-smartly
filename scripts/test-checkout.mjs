 await db.exec(`grant select,insert,update,delete on all tables in schema public to authenticated;
 insert into auth.users(id,email) values('${buyer}','buyer@example.test'),('${admin}','admin@example.test'),('${other}','other@example.test');
 insert into public.user_roles(user_id,role) values('${admin}','admin');
 insert into public.products(id,name,price,discounted_price,stock) values('${product}','Article test',1000,800,5);
 insert into public.cart_items(user_id,product_id,quantity) values('${buyer}','${product}',2);`);
 await migration('20261012000001_gallery_and_profile_security.sql');
